-- 0025_comment_avatars_replies.sql
-- 1) 评论 / 留言支持访客头像：小尺寸 WebP data URL 存 DB，
--    不开放匿名 Storage 写权限，避免被刷存储。
-- 2) 新增 replies 表：游客可回复评论 / 留言；
--    与博主回复（comments.reply / guestbook_messages.reply）分开存储与展示。
-- 幂等；在 Supabase SQL Editor 手动执行。

alter table public.comments
  add column if not exists avatar_data text;

alter table public.guestbook_messages
  add column if not exists avatar_data text;

create table if not exists public.replies (
  id          bigint generated by default as identity primary key,
  target_type text not null check (target_type in ('comment', 'guestbook')),
  target_id   bigint not null,
  name        text not null default '匿名',
  avatar_data text,
  content     text not null,
  ip          text,
  created_at  timestamptz not null default now()
);

create index if not exists replies_target_idx
  on public.replies (target_type, target_id, created_at);

alter table public.replies enable row level security;

-- 任何人可读
drop policy if exists replies_select_public on public.replies;
create policy replies_select_public on public.replies
  for select to anon, authenticated using (true);

-- 匿名可插入（限流与内容校验在 Server Action 内完成）
drop policy if exists replies_insert_public on public.replies;
create policy replies_insert_public on public.replies
  for insert to anon, authenticated with check (true);

-- 仅博主可删
drop policy if exists replies_delete_admin on public.replies;
create policy replies_delete_admin on public.replies
  for delete to authenticated using (public.is_admin());

-- 表级权限
grant select, insert on public.replies to anon, authenticated;
grant delete on public.replies to authenticated;
grant usage, select on sequence public.replies_id_seq to anon, authenticated;
